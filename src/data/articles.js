export function getArticleBySlug(slug) {
  return ARTICLES.find((article) => article.slug === slug);
}

export function getRelatedArticles(slug, limit = 3) {
  const current = getArticleBySlug(slug);
  if (!current) return ARTICLES.slice(0, limit);

  const related = ARTICLES.filter(
    (article) =>
      article.slug !== slug &&
      article.tags.some((tag) => current.tags.includes(tag))
  );

  const extras = ARTICLES.filter(
    (article) => article.slug !== slug && !related.includes(article)
  );

  return [...related, ...extras].slice(0, limit);
}
